import { build } from "esbuild"
import { readFileSync } from "node:fs"
import { mkdirSync } from "node:fs"

const outfile = "supabase/functions/submit-web-chat/submission.ts"
const banner = "// Generated by scripts/vendor-submit-web-chat.mjs from src/services/webChat/submission.ts. Do not edit by hand.\n"

const result = await build({
  entryPoints: ["src/services/webChat/submission.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  write: false,
  legalComments: "none",
  banner: { js: banner },
  logLevel: "silent",
})
const generated = result.outputFiles[0]?.text ?? ""
if (!generated.includes("export {\n")) {
  console.error("The vendored submission bundle did not export its functions.")
  process.exit(1)
}
const check = process.argv.includes("--check")
if (check) {
  const committed = readFileSync(outfile, "utf8")
  if (committed !== generated) {
    console.error(`${outfile} does not match src/services/webChat/submission.ts. Run: node scripts/vendor-submit-web-chat.mjs`)
    process.exit(1)
  }
  process.exit(0)
}
mkdirSync("supabase/functions/submit-web-chat", { recursive: true })
const { writeFileSync } = await import("node:fs")
writeFileSync(outfile, generated)
console.log(`Wrote ${outfile} (${generated.length} bytes)`)
