import { build } from "esbuild"
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname } from "node:path"

const outfile = "supabase/functions/paper-text/bundle/index.ts"
const banner = "// Generated by scripts/bundle-paper-text.mjs. Shared src modules are inlined. unpdf stays external.\n"

const result = await build({
  entryPoints: ["supabase/functions/paper-text/index.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  external: ["unpdf"],
  write: false,
  legalComments: "none",
  banner: { js: banner },
  logLevel: "silent",
})
const generated = result.outputFiles[0]?.text ?? ""
const problems = []
if (!/from\s+["']unpdf["']/.test(generated)) problems.push("the bundle must import unpdf and leave it external")
if (generated.includes("../../../src") || generated.includes("from \"../")) problems.push("the bundle must inline the shared src modules")
if (generated.includes("npm:unpdf")) problems.push("the bundle imports unpdf by name; deno.json maps it to npm:unpdf@2.2.3")
if (generated.length > 800_000) problems.push("unpdf was inlined; mark it external")
if (problems.length) {
  console.error(problems.join("\n"))
  process.exit(1)
}
if (process.argv.includes("--check")) {
  console.log(`paper-text bundle ok (${generated.length} bytes, unpdf external, import map npm:unpdf@2.2.3)`)
  process.exit(0)
}
mkdirSync(dirname(outfile), { recursive: true })
writeFileSync(outfile, generated)
console.log(`Wrote ${outfile} (${generated.length} bytes). Deploy it with supabase/functions/paper-text/deno.json (npm:unpdf@2.2.3).`)
